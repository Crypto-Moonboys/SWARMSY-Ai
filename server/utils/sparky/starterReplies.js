function normalizeStarterMessage(message = "") {
  return String(message).trim().replace(/\s+/g, " ");
}

function getSparkyStarterReply(workspace = null, message = "") {
  if (workspace?.slug !== SPARKY_WORKSPACE_SLUG) return null;
  const normalizedMessage = normalizeStarterMessage(message);
  const starterMessage = Object.keys(STARTER_REPLIES).find(
    (starter) => normalizeStarterMessage(starter) === normalizedMessage
  );
  return starterMessage ? STARTER_REPLIES[starterMessage] : null;
}

